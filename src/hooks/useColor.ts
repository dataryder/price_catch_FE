// Minimal replacement for d3-scale-chromatic / d3-interpolate:
// uniform B-spline interpolation through a list of hex colors (same math as
// d3's interpolateRgbBasis, which backs interpolateRdYlGn).

const hexToRgb = (hex: string): [number, number, number] => {
  const n = parseInt(hex.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};

const basis = (t1: number, v0: number, v1: number, v2: number, v3: number) => {
  const t2 = t1 * t1;
  const t3 = t2 * t1;
  return (
    ((1 - 3 * t1 + 3 * t2 - t3) * v0 +
      (4 - 6 * t2 + 3 * t3) * v1 +
      (1 + 3 * t1 + 3 * t2 - 3 * t3) * v2 +
      t3 * v3) /
    6
  );
};

const splineChannel = (values: number[]) => {
  const n = values.length - 1;
  return (t: number) => {
    const i = t <= 0 ? ((t = 0), 0) : t >= 1 ? ((t = 1), n - 1) : Math.floor(t * n);
    const v1 = values[i];
    const v2 = values[i + 1];
    const v0 = i > 0 ? values[i - 1] : 2 * v1 - v2;
    const v3 = i < n - 1 ? values[i + 2] : 2 * v2 - v1;
    return basis((t - i / n) * n, v0, v1, v2, v3);
  };
};

const clamp = (v: number) => Math.max(0, Math.min(255, Math.round(v)));

const rgbBasis = (colors: string[]) => {
  const rgb = colors.map(hexToRgb);
  const [r, g, b] = [0, 1, 2].map((c) => splineChannel(rgb.map((x) => x[c])));
  return (t: number) => `rgb(${clamp(r(t))}, ${clamp(g(t))}, ${clamp(b(t))})`;
};

const schemes = {
  // generated by changing lightness based on primary blue (oklch)
  blues: rgbBasis([
    "#fafcff", // 99%
    "#e6efff", // 95%
    "#cddfff", // 90%
    "#9bbeff", // 80%
    "#699bff", // 70%
    "#3575fe", // 60%
    "#2563EB", // Blue 600
    "#0036b0", // 40%
    "#000e42", // 20%
  ]),
  // ColorBrewer RdYlGn (11 classes), as used by d3's interpolateRdYlGn
  rdYlGn: rgbBasis([
    "#a50026", "#d73027", "#f46d43", "#fdae61", "#fee08b", "#ffffbf",
    "#d9ef8b", "#a6d96a", "#66bd63", "#1a9850", "#006837",
  ]),
};

export type Color = keyof typeof schemes;

export const useColor = (key: Color) => {
  const interpolate = (
    value: number | null,
    domain: [min: number, max: number] | null = null,
  ): string => {
    if (value === null) return "#ffffff00"; // transparent
    if (domain !== null) {
      if (domain[1] === domain[0]) return schemes[key](0.5); // Prevent NaN division by zero
      return schemes[key]((value - domain[0]) / (domain[1] - domain[0]));
    }
    return schemes[key](value);
  };

  return { interpolate };
};
